const {_electron} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const sharp = require('sharp');
const {Store} = require('../src/core.cjs');

(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'srm-chrome-ui-')); let app;
  try {
    const store = new Store(dir); store.data.settings.autoScan = false; store.save();
    const preview = 'data:image/jpeg;base64,' + (await sharp({create: {width: 160, height: 160, channels: 3, background: '#d5e6f0'}}).jpeg().toBuffer()).toString('base64');
    app = await _electron.launch({args: ['.'], cwd: path.resolve(__dirname, '..'), env: {...process.env, SRM_DATA_DIR: dir, SRM_DRIVER: '1'}});
    const page = await app.firstWindow(); await page.waitForFunction(() => typeof renderStudio === 'function');
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const initial = await page.evaluate(() => window.srm.call('snapshot'));
    await app.evaluate(({ipcMain, BrowserWindow}, {initial, preview, dir}) => {
      const item = id => ({id, shop: 'shop.ui', productId: id, sourceName: 'Bài ' + id, name: 'Tên mới ' + id, contentApproved: true, notionUrl: 'https://app.notion.com/p/' + id.padStart(32, 'a'), status: 'published', imageFiles: [], price: 100000});
      globalThis.chromeUISnapshot = {...initial, studio: {...initial.studio, busy: false, jobs: [item('111'), item('222')]}, studioChrome: {listening: true, connected: false, remembered: false, message: 'Chưa kết nối tiện ích Chrome.', busy: false, completed: 0}};
      globalThis.chromeUICalls = {paired: 0, disconnected: 0, folders: 0, refs: [], run: []};
      const emit = () => { const s=globalThis.chromeUISnapshot; s.studioChatgpt={...s.studioChrome}; s.studio.busy=s.studioChrome.busy; s.studio.progress=s.studioChrome.progress; BrowserWindow.getAllWindows()[0].webContents.send('state', structuredClone(s)); };
      const handle = (name, fn) => {ipcMain.removeHandler(name); ipcMain.handle(name, async (_event, ...args) => ({ok: true, value: await fn(...args)}));};
      handle('snapshot', () => structuredClone(globalThis.chromeUISnapshot));
      handle('studio-chrome-extension-folder', () => {globalThis.chromeUICalls.folders++; return {};});
      handle('studio-chrome-pair', () => {globalThis.chromeUICalls.paired++; return {code: '12345678', expiresAt: null, oneTime: true};});
      handle('studio-chrome-disconnect', () => {globalThis.chromeUICalls.disconnected++; Object.assign(globalThis.chromeUISnapshot.studioChrome, {connected: false, remembered: false, ready: false, message: 'Đã ngắt Chrome.'}); emit(); return {};});
      handle('studio-image-reference-pick', id => {globalThis.chromeUICalls.refs.push(id); return {selectionId: 'reference-' + id, name: '<img src=x>.png', previewDataUrl: preview};});
      handle('studio-image-pick', (id, index) => ({selectionId: 'manual-' + id + '-' + index, name: 'anh-thu-cong-cu.jpg', previewDataUrl: preview, width: 1024, height: 1024, bytes: 23456}));
      handle('studio-image-prompts', id => ({jobId: id, contentDigest: 'a'.repeat(64), prompts: Array.from({length: 5}, (_, index) => ({title: 'Ảnh ' + (index + 1), text: 'Prompt ' + id + ' ảnh ' + (index + 1)}))}));
      handle('studio-cdp-run', async (id, selection, digest) => {
        globalThis.chromeUICalls.run.push({id, selection, digest});
        globalThis.chromeUISnapshot.studio.jobs.find(item => item.id === id).imageSource = 'chrome-cdp';
        globalThis.chromeUISnapshot.studioChrome = {...globalThis.chromeUISnapshot.studioChrome, connected: true, busy: true, jobId: id, progress: 'Đang chờ ảnh 1', completed: 0}; emit();
        await new Promise(resolve => {globalThis.completeChromeUIRun = resolve;});
        globalThis.chromeUISnapshot.studioChrome.busy = false; emit(); return {};
      });
      globalThis.advanceChromeUIImage = (count, sparse = false) => {
        const item = globalThis.chromeUISnapshot.studio.jobs[0];
        item.imageFiles = Array.from({length: count}, (_, index) => ({index: sparse ? index + 2 : index, filename: (index + 1) + '.jpg', previewDataUrl: preview, bytes: 23456, width: 1024, height: 1024}));
        if (count === 5) {item.localFolder = dir; item.status = 'images-ready';}
        Object.assign(globalThis.chromeUISnapshot.studioChrome, {completed: count, progress: 'Đã lưu ảnh ' + count}); emit();
      };
      globalThis.connectChromeUI = (ready = true) => {Object.assign(globalThis.chromeUISnapshot.studioChrome, {connected: true, remembered: true, ready, message: 'Đã kết nối tiện ích Chrome.'}); emit();};
      globalThis.rememberChromeUI = () => {Object.assign(globalThis.chromeUISnapshot.studioChrome, {connected: false, remembered: true, ready: false, message: 'Đã nhớ Chrome trên máy này.'}); emit();};
    }, {initial, preview, dir});
    await page.reload(); await page.locator('nav [data-tab="replacements"]').click();
    assert.equal(await page.locator('#studio-settings').isHidden(), true);
    await page.locator('#studio-settings').evaluate(el => { el.hidden = false; el.open = true; });
    assert.equal(await page.locator('#studio-settings').evaluate(el => el.open), true);
    assert.equal(await page.locator('#studio-settings').evaluate(el => el.parentElement.firstElementChild === el), true, 'settings lead the Studio');
    assert.equal(await page.locator('#studio-cdp-legacy').isHidden(), true);
    assert.equal(await page.locator('#studio-chatgpt-advanced').isVisible(), true);
    assert.equal(await page.locator('#studio-extension-legacy').isHidden(),true);
    await page.locator('#studio-extension-legacy').evaluate(el=>{el.hidden=false;el.open=true;});
    await page.locator('#studio-chrome-extension-folder').click();
    assert.equal(await app.evaluate(() => globalThis.chromeUICalls.folders), 1);
    await page.locator('#studio-chrome-pair').click();
    await page.waitForFunction(() => document.querySelector('#studio-chrome-pair-code').textContent === '12345678');
    assert.equal(await page.locator('#studio-chrome-pair-expiry').textContent(), 'Không hết hạn · dùng một lần');
    await page.waitForTimeout(1600);
    assert.equal(await page.locator('#studio-chrome-pair-code').textContent(), '12345678', 'one-time code without expiry remains available until pairing');
    await app.evaluate(() => globalThis.connectChromeUI());
    await page.waitForFunction(() => document.querySelector('#studio-chrome-pair-panel').hidden);
    assert.equal(await page.locator('#studio-chrome-pair-code').textContent(), '', 'consumed code is removed from the DOM');
    assert.equal(await page.locator('#studio-chrome-pair').isDisabled(), true, 'remembered pairing cannot be replaced accidentally');
    await app.evaluate(() => globalThis.rememberChromeUI()); await page.reload(); await page.locator('nav [data-tab="replacements"]').click();
    await page.locator('#studio-settings').evaluate(el => { el.hidden = false; el.open = true; });
    await page.locator('#studio-extension-legacy').evaluate(el=>{el.hidden=false;el.open=true;});
    assert.match(await page.locator('#studio-chrome-connection-status').textContent(), /không cần nhập mã/);
    assert.equal(await page.locator('#studio-chrome-pair-code').textContent(), '', 'remembered connection survives render/reload without another code');
    assert.equal(await page.locator('#studio-chrome-pair').isDisabled(), true);
    assert.equal(await page.locator('#studio-chrome-disconnect').isEnabled(), true);
    await page.locator('#studio-step-2').click(); await page.locator('#studio-image-job').selectOption('111');
    assert.match(await page.locator('#studio-chrome-progress').textContent(), /Mở Chrome riêng/);
    await page.locator('#studio-chrome-disconnect').click();
    await page.waitForFunction(() => !document.querySelector('#studio-chrome-pair').disabled);
    assert.equal(await app.evaluate(() => globalThis.chromeUICalls.disconnected), 1);
    assert.equal(await page.locator('#studio-chrome-disconnect').isDisabled(), true);
    await page.locator('#studio-step-2').click(); await page.locator('#studio-image-job').selectOption('111');
    assert.equal(await page.locator('#studio-manual-fallback').evaluate(el => el.open), false);
    assert.equal(await page.locator('#studio-import-images').isVisible(), false);
    assert.equal(await page.locator('#studio-gallery').isVisible(), true);
    assert.equal(await page.locator('#studio-attach').isHidden(), true);
    assert.equal(await page.locator('#studio-chrome-run').isDisabled(), true);
    assert.equal(await page.locator('#studio-chrome-run').textContent(), 'Tạo lần lượt 5 ảnh');
    await page.locator('#studio-image-reference-pick').click();
    await page.waitForFunction(() => document.querySelectorAll('#studio-image-reference-preview img').length === 1);
    assert.equal(await page.locator('#studio-image-reference-name img').count(), 0, 'reference filename cannot become HTML');
    await page.locator('#studio-manual-prompts').click();
    await page.waitForFunction(() => !document.querySelector('#studio-manual-prompts').disabled);
    assert.equal(await page.locator('#studio-chrome-run').isDisabled(), true, 'a paired Chrome connection is required');
    await page.locator('#studio-manual-fallback').evaluate(el => { el.hidden = false; });
    await page.locator('#studio-manual-fallback summary').click();
    await page.locator('#studio-manual-selectors [data-studio-image-slot="0"]').click();
    await page.waitForFunction(() => document.querySelectorAll('#studio-gallery img').length === 1);
    await page.locator('#studio-image-job').selectOption('222');
    assert.equal(await page.locator('#studio-image-reference-preview img').count(), 0, 'reference selection does not cross job boundaries');
    assert.equal(await page.locator('#studio-image-prompt-text').inputValue(), '');
    await page.locator('#studio-image-job').selectOption('111'); await app.evaluate(() => globalThis.connectChromeUI(false));
    assert.equal(await page.locator('#studio-chrome-run').isDisabled(), true, 'a connected tab with a gate or active draft cannot start');
    await app.evaluate(() => globalThis.connectChromeUI());
    await page.waitForFunction(() => !document.querySelector('#studio-chrome-run').disabled);
    assert.match(await page.locator('#studio-chrome-progress').textContent(), /prompt 1; lưu xong mới gửi prompt tiếp theo/);
    await page.locator('#studio-chrome-run').click();
    await page.waitForFunction(() => document.querySelector('#studio-chrome-progress').textContent.includes('Đang chờ ảnh 1'));
    assert.equal(await page.locator('#studio-chrome-disconnect').isDisabled(), true, 'active image bridge cannot be disconnected');
    assert.equal(await page.locator('#studio-gallery img').count(), 0, 'old manual previews cannot cover the new Chrome results');
    assert.equal(await page.locator('#studio-image-job').isDisabled(), true, 'job identity is locked during the pending run');
    await app.evaluate(() => globalThis.advanceChromeUIImage(1, true));
    await page.waitForFunction(() => document.querySelectorAll('#studio-gallery img').length === 1);
    assert.equal(await page.locator('#studio-gallery figure').nth(2).locator('img').count(), 1, 'explicit image index reserves the correct gallery slot');
    assert.equal(await page.locator('#studio-go-step3').isHidden(), true, 'partial image progress does not expose step 3 navigation');
    await app.evaluate(() => globalThis.advanceChromeUIImage(5));
    await page.waitForFunction(() => document.querySelectorAll('#studio-gallery img').length === 5);
    assert.equal(await page.locator('#studio-go-step3').isVisible(), true);
    await page.locator('#studio-go-step3').click();
    assert.equal(await page.locator('#studio-attach').isVisible(), true);
    assert.equal(await page.locator('#studio-attach').isDisabled(), true, 'attachment waits for the pending run to settle');
    await app.evaluate(() => globalThis.completeChromeUIRun());
    await page.waitForFunction(() => !document.querySelector('#studio-attach').disabled);
    const calls = await app.evaluate(() => globalThis.chromeUICalls);
    assert.deepEqual(calls.run, [{id: '111', selection: 'reference-111', digest: 'a'.repeat(64)}]);
    for (const width of [1440, 780, 390]) {
      await app.evaluate(({BrowserWindow}, width) => {const window = BrowserWindow.getAllWindows()[0]; window.setMinimumSize(360, 500); window.setSize(width, 1000);}, width);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Chrome Studio fits viewport ' + width);
    }
    assert.deepEqual(errors, []);
    console.log('PASS Chrome Studio UI: one-time code without expiry, remembered pairing and disconnect lock, per-job reference/digest, sequential image label, isolated CDP primary, streaming indexed gallery and verified five-image Notion gate. Remote Chrome behavior is mocked.');
  } finally {
    if (app) await app.close();
    assert.ok(dir.startsWith(path.join(os.tmpdir(), 'srm-chrome-ui-'))); fs.rmSync(dir, {recursive: true, force: true});
  }
})().catch(error => {console.error(error); process.exitCode = 1;});
